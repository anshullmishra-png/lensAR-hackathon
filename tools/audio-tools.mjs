// Helpers for the Hindi voice clips. Zero dependencies; needs the same Node as run-tests.mjs.
//
//   node tools/audio-tools.mjs script   print every clip: file name, the Hindi line to record, the English meaning
//   node tools/audio-tools.mjs index    scan Assets/Audio and write Assets/Scripts/audio/AudioIndex.ts
//
// Record one file per id (MP3 or WAV) into Assets/Audio/, e.g. l1_a.mp3, then run `index` once.
// Lens Studio imports the files by itself; AudioManager finds them by file name.
import {existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync} from "node:fs"
import {registerHooks, stripTypeScriptTypes} from "node:module"
import path from "node:path"
import {fileURLToPath, pathToFileURL} from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const audioDir = path.join(root, "Assets", "Audio")
const indexFile = path.join(root, "Assets", "Scripts", "audio", "AudioIndex.ts")

registerHooks({
  resolve(specifier, context, nextResolve) {
    const relative = specifier.startsWith("./") || specifier.startsWith("../")
    if (relative && !path.extname(specifier) && context.parentURL) {
      const candidate = path.resolve(path.dirname(fileURLToPath(context.parentURL)), `${specifier}.ts`)
      if (existsSync(candidate)) {
        return {url: pathToFileURL(candidate).href, shortCircuit: true}
      }
    }
    return nextResolve(specifier, context)
  },
  load(url, context, nextLoad) {
    if (url.endsWith(".ts")) {
      const source = readFileSync(fileURLToPath(url), "utf8")
      return {format: "module", source: stripTypeScriptTypes(source, {mode: "transform"}), shortCircuit: true}
    }
    return nextLoad(url, context)
  }
})

const isText = (v) => v && typeof v === "object" && typeof v.hi === "string" && typeof v.en === "string"

/** Every spoken line, in play order: [{id, hi, en}]. */
async function collectClips() {
  const {Content} = await import(pathToFileURL(path.join(root, "Assets", "Scripts", "content", "Content.ts")).href)
  const clips = new Map()
  const add = (id, t) => {
    if (typeof id === "string" && isText(t) && !clips.has(id)) {
      clips.set(id, {id, hi: t.hi, en: t.en})
    }
  }
  const walk = (node) => {
    if (Array.isArray(node)) {
      node.forEach(walk)
      return
    }
    if (!node || typeof node !== "object" || isText(node)) {
      return
    }
    if (typeof node.audioId === "string") {
      add(node.audioId, node.text ?? node.explanation)
    } else if (typeof node.id === "string") {
      if (isText(node.explanation)) {
        add(node.id, node.explanation)
      } else if (isText(node.text) && /^(l1_|l2_|l3_|m_|end_)/.test(node.id)) {
        add(node.id, node.text)
      }
    }
    Object.values(node).forEach(walk)
  }
  walk(Content)
  return [...clips.values()]
}

const [, , command] = process.argv

if (command === "script") {
  const clips = await collectClips()
  console.log(`${clips.length} voice clips to record (plus sfx_right and sfx_wrong, which are short sounds, not speech).\n`)
  clips.forEach((c, i) => {
    console.log(`${String(i + 1).padStart(2)}. ${c.id}.mp3`)
    console.log(`    HI: ${c.hi}`)
    console.log(`    EN: ${c.en}\n`)
  })
} else if (command === "index") {
  mkdirSync(audioDir, {recursive: true})
  const files = readdirSync(audioDir).filter((f) => /\.(mp3|wav)$/i.test(f)).sort()
  const entries = files.map((f) => `  ${JSON.stringify(f.replace(/\.[^.]+$/, ""))}: requireAsset("../../Audio/${f}") as AudioTrackAsset`)
  const body = `// GENERATED by \`node tools/audio-tools.mjs index\`. Do not edit by hand.
// Maps an audioId (the file name without extension) to the clip in Assets/Audio.
export const AUDIO_TRACKS: {[audioId: string]: AudioTrackAsset} = {
${entries.join(",\n")}${entries.length ? "\n" : ""}}
`
  writeFileSync(indexFile, body)
  console.log(`Wrote ${path.relative(root, indexFile)} with ${files.length} clip(s)${files.length ? ": " + files.join(", ") : ""}.`)
} else {
  console.log("usage: node tools/audio-tools.mjs script | index")
  process.exitCode = 1
}
